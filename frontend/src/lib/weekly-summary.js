// The weekly summary — one notification on the evening of the last day of your week: how many
// workouts, how much weight, how many records, and where a training block stands. Opt-in, under
// the workout-day reminder (S.reminder.summary), like the missed-workout nudge.
//
// The self-hosted app sends it as a web push from the server (api/weekly-summary.js, a hand copy
// of the rules below, as api/nudge.js is of lib/nudge.js); the mobile build schedules it as a
// native local notification (lib/mobile.js), rescheduled with every save so its numbers follow
// what you log. Both answer the same questions the same way:
//
//   WHEN  — at 19:00 on the user's clock on the week's last day (Sunday for a Monday week,
//           Saturday for a Sunday week). The server sends a late one until 21:30, once per week.
//   WHAT  — the workouts dated in that week. The volume is the one each workout shows: the phone
//           counts it the way the app does (history.js sessionVolume); the server, which has no
//           copy of that, reads the total saved with each workout (`w.vol`).
//   A WEEK WITHOUT WORKOUTS — still a summary, a short one, so turning it on is never silent.
//
// Copy: keys are the English source strings; api/summary-copy.js carries the server's copy of
// their translations (generated by api/scripts/build-summary-copy.mjs, a test keeps them equal).
import { weekKey, weekStartOf, weekDayOffset } from './format.js'
import { sessionVolume } from './history.js'
import { blockWeekOf } from './blocks.js'

export const SUMMARY_MINUTE = 19 * 60

export const SUMMARY_COPY = {
  title: 'Your week',
  none: 'No workouts this week. A new week starts tomorrow.',
  workouts: ['{0} workout', '{0} workouts'],
  lifted: '{0} lifted',
  prs: ['{0} PR', '{0} PRs'],
  week: 'Week {0} of {1}',
}

const dayOf = iso => new Date(iso + 'T12:00:00').getDay()

/** Whether a date is the last day of the profile's week. */
export const isLastDayOfWeek = (S, iso) => weekDayOffset(dayOf(iso), weekStartOf(S)) === 6

/** The week `iso` falls in: { workouts, volume, prs, block: { week, of } | null }. */
export function weekSummary(S, iso) {
  const key = weekKey(iso, weekStartOf(S))
  const week = (Array.isArray(S?.workouts) ? S.workouts : []).filter(w => w && typeof w.d === 'string' && weekKey(w.d, weekStartOf(S)) === key)
  const b = blockWeekOf(S, iso)
  return {
    workouts: week.length,
    volume: Math.round(week.reduce((n, w) => n + sessionVolume(w, S), 0)),
    prs: week.reduce((n, w) => n + (Array.isArray(w.prs) ? w.prs.length : 0), 0),
    block: b ? { week: b.week, of: b.of } : null,
  }
}

/**
 * The notification text, built with the translation functions handed in (lib/i18n.js t and tn on
 * the phone; the server has its own over api/summary-copy.js) and a number formatter.
 */
export function summaryText(sum, unit, { t, tn, num }) {
  const title = t(SUMMARY_COPY.title)
  if (!sum.workouts) return { title, body: t(SUMMARY_COPY.none) }
  const parts = [tn(...SUMMARY_COPY.workouts, sum.workouts)]
  if (sum.volume > 0) parts.push(t(SUMMARY_COPY.lifted, num(sum.volume) + ' ' + unit))
  if (sum.prs > 0) parts.push(tn(...SUMMARY_COPY.prs, sum.prs))
  if (sum.block) parts.push(t(SUMMARY_COPY.week, sum.block.week, sum.block.of))
  return { title, body: parts.join(' · ') }
}
