#!/usr/bin/env node
// Writes api/summary-copy.js — the server's copy of the weekly summary text — from the source of
// truth in the frontend: SUMMARY_COPY in frontend/src/lib/weekly-summary.js and its translations
// in frontend/src/locales, the way build-nudge-copy.mjs does it for the nudge
// (test/summary-copy.test.js fails when the two have drifted).
//
//   node scripts/build-summary-copy.mjs          # rewrite summary-copy.js
//   node scripts/build-summary-copy.mjs --check  # exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const API = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONT = path.join(API, '..', 'frontend', 'src');
const OUT = path.join(API, 'summary-copy.js');

export async function buildSummaryCopy() {
  const { SUMMARY_COPY } = await import(pathToFileURL(path.join(FRONT, 'lib', 'weekly-summary.js')));
  const langs = fs.readdirSync(path.join(FRONT, 'locales')).filter(f => /^[a-zA-Z-]+\.js$/.test(f)).map(f => f.slice(0, -3)).sort();
  // A plural is { one, other } in English and in a pack that writes it as two keys, or the pack's
  // own forms ({ one, few, many }) where it has them, as lib/i18n-core.js tn reads them.
  const forms = (pack, [one, other]) => {
    const v = pack[other];
    return v && typeof v === 'object' ? v : { one: pack[one] || one, other: v || other };
  };
  const copyOf = pack => ({
    title: pack[SUMMARY_COPY.title] || SUMMARY_COPY.title,
    none: pack[SUMMARY_COPY.none] || SUMMARY_COPY.none,
    lifted: pack[SUMMARY_COPY.lifted] || SUMMARY_COPY.lifted,
    week: pack[SUMMARY_COPY.week] || SUMMARY_COPY.week,
    workouts: forms(pack, SUMMARY_COPY.workouts),
    prs: forms(pack, SUMMARY_COPY.prs),
  });
  const copy = { en: copyOf({}) };
  for (const lang of langs) copy[lang] = copyOf((await import(pathToFileURL(path.join(FRONT, 'locales', lang + '.js')))).default);
  return '// GENERATED by scripts/build-summary-copy.mjs from frontend/src/lib/weekly-summary.js and frontend/src/locales.\n'
    + '// Do not edit by hand: change the frontend strings and run the script again.\n'
    + 'export const SUMMARY_COPY = ' + JSON.stringify(copy, null, 2) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildSummaryCopy();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('api/summary-copy.js is out of date: run node scripts/build-summary-copy.mjs'); process.exit(1); }
    console.log('api/summary-copy.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT));
  }
}
